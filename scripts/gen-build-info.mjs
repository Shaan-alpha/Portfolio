// Stamps the current commit into src/lib/buildInfo.ts so the hero can print a
// build id that is actually checkable. Runs from the `prebuild`/`predev` hooks.
//
// A plain generated module rather than next.config's `env` block: the value is
// a normal typed import, so a missing or stale stamp is a build error you can
// see rather than an empty string silently rendered into the page.

import { execSync } from "node:child_process";
import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const target = join(root, "src", "lib", "buildInfo.ts");

function sha() {
  try {
    return execSync("git rev-parse --short HEAD", {
      cwd: root,
      stdio: ["ignore", "pipe", "ignore"],
    })
      .toString()
      .trim();
  } catch {
    // A tarball export or a CI checkout without git history still has to build.
    return "unknown";
  }
}

const contents = `// GENERATED by scripts/gen-build-info.mjs — do not edit by hand.
export const BUILD_SHA = ${JSON.stringify(sha())};
`;

// Only write when it actually changed, so a no-op build leaves the tree clean.
const current = existsSync(target) ? readFileSync(target, "utf8") : "";
if (current !== contents) {
  writeFileSync(target, contents, "utf8");
  console.log(`build-info: ${sha()}`);
} else {
  console.log(`build-info: ${sha()} (unchanged)`);
}
